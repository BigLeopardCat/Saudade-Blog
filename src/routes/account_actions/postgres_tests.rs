struct PgContext {
    admin: sea_orm::DatabaseConnection,
    state: std::sync::Arc<crate::routes::AppState>,
    schema: String,
    url: String,
}
impl PgContext {
    async fn new(url: String) -> Self {
        use sea_orm::Database;
        let admin = Database::connect(url.clone())
            .await
            .expect("explicit test PostgreSQL must connect");
        let schema = format!("account_actions_{}", uuid::Uuid::new_v4().simple());
        sql(&admin, &format!("CREATE SCHEMA {schema}")).await;
        let db = scoped_db(&url, &schema).await;
        sql(&db, r#"CREATE TABLE "user" (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username varchar(255) UNIQUE NOT NULL, nickname varchar(255) NOT NULL DEFAULT '',
            nickname_auto_renamed smallint NOT NULL DEFAULT 0, avatar varchar(255),
            password varchar(255) NOT NULL DEFAULT 'sensitive-password', role varchar(32) NOT NULL DEFAULT 'user',
            status smallint NOT NULL DEFAULT 0, token_version integer NOT NULL DEFAULT 0,
            chat_quota_used integer NOT NULL DEFAULT 0, muted_until timestamp);
            CREATE TABLE user_notification (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id integer NOT NULL REFERENCES "user"(id),
                announcement_id integer, type varchar(32) NOT NULL, title varchar(128) NOT NULL, content text,
                link varchar(255), is_read boolean NOT NULL DEFAULT false, read_at timestamp,
                deleted_at timestamp, created_at timestamp NOT NULL);
        "#).await;
        // Apply the real numbered migration, including its trigger, in a fresh isolated schema.
        sql(
            &db,
            include_str!("../../../scripts/migration/pg/0017_account_action_version.sql"),
        )
        .await;
        sql(&db, "INSERT INTO \"user\"(id,username,nickname,role) VALUES (1,'root','root','superadmin'),(2,'exact_user','same','user'),(3,'exact_user_extra','same','user'),(4,'operator','op','admin'),(5,'otheradmin','admin','admin')").await;
        Self {
            admin,
            state: std::sync::Arc::new(state(db)),
            schema,
            url,
        }
    }
    async fn close(self) {
        self.state.db.close_by_ref().await.unwrap();
        sql(&self.admin, &format!("DROP SCHEMA {} CASCADE", self.schema)).await;
    }
}
async fn scoped_db(url: &str, schema: &str) -> sea_orm::DatabaseConnection {
    let mut options = sea_orm::ConnectOptions::new(url.to_owned());
    options
        .max_connections(3)
        .set_schema_search_path(schema.to_owned());
    sea_orm::Database::connect(options).await.unwrap()
}
async fn sql(db: &sea_orm::DatabaseConnection, statement: &str) {
    use sea_orm::ConnectionTrait;
    db.execute_unprepared(statement).await.unwrap();
}
fn headers(id: i32, version: i32) -> axum::http::HeaderMap {
    let mut headers = axum::http::HeaderMap::new();
    headers.insert(
        "authorization",
        format!(
            "Bearer {}",
            crate::auth_jwt::create_token(id, "superadmin", version)
        )
        .parse()
        .unwrap(),
    );
    headers
}
async fn read(db: &sea_orm::DatabaseConnection, id: i32) -> user::Model {
    use sea_orm::EntityTrait;
    user::Entity::find_by_id(id).one(db).await.unwrap().unwrap()
}
async fn notice_count(db: &sea_orm::DatabaseConnection, id: i32) -> u64 {
    use sea_orm::{ColumnTrait, EntityTrait, PaginatorTrait, QueryFilter};
    crate::entity::user_notification::Entity::find()
        .filter(crate::entity::user_notification::Column::UserId.eq(id))
        .count(db)
        .await
        .unwrap()
}
async fn prepared(ctx: &PgContext, id: i32, intent: &Intent) -> Prepared {
    let actor = read(&ctx.state.db, id).await;
    let Json(response) = prepare(
        State(ctx.state.clone()),
        headers(id, actor.token_version),
        Json(intent.clone().into()),
    )
    .await;
    assert_eq!(response.code, 200, "{}", response.message);
    assert_eq!(response.data.intent.as_ref(), Some(intent));
    response.data.plan
}

#[tokio::test]
async fn postgres_plans_conflicts_policies_and_legacy_effects_are_atomic() {
    use sea_orm::{ConnectionTrait, EntityTrait};
    let Ok(url) = std::env::var("TEST_PG_URL") else {
        eprintln!("account-actions PostgreSQL test skipped: TEST_PG_URL is not set");
        return;
    };
    std::env::set_var("JWT_SECRET", "test-secret-not-used-for-anything-real");
    let ctx = PgContext::new(url).await;
    let db = &ctx.state.db;
    let mut freeze = intent("freeze");
    freeze.target = Target {
        id: Some(2),
        username: Some("exact_user".into()),
    };
    let plan = prepared(&ctx, 1, &freeze).await;
    assert_eq!(
        (plan.before.id, plan.before.status, plan.after.status),
        (2, 0, 1)
    );
    assert!(plan.changed && plan.revoke_sessions && plan.notification_count == 1);
    assert_eq!(read(db, 2).await.status, 0, "prepare must not write");
    assert_eq!(notice_count(db, 2).await, 0);
    let mut mismatch = freeze.clone();
    mismatch.target.username = Some("another_account".into());
    assert!(targets::prepare(db, 1, Some(0), &mismatch, false)
        .await
        .is_err());
    assert_eq!(
        read(db, 3).await.status,
        0,
        "full name is exact, not prefix"
    );
    let mut missing = freeze.clone();
    missing.target.username = Some("same".into());
    assert!(
        execute(&ctx.state, &headers(1, 0), &missing, None)
            .await
            .is_err(),
        "nickname never resolves"
    );
    let changed = execute(&ctx.state, &headers(1, 0), &freeze, Some(&plan.version))
        .await
        .unwrap();
    assert_eq!(changed.state, plan);
    assert_eq!(
        (read(db, 2).await.status, read(db, 2).await.token_version),
        (1, 1)
    );
    assert_eq!(notice_count(db, 2).await, 1);
    let notice = crate::entity::user_notification::Entity::find_by_id(1)
        .one(db)
        .await
        .unwrap()
        .unwrap();
    assert!(
        (notice.created_at - targets::now()).num_seconds().abs() < 3,
        "notification time follows Shanghai, not host TZ"
    );

    // Same confirmed version cannot write again even when the first HTTP response was discarded.
    assert!(
        execute(&ctx.state, &headers(1, 0), &freeze, Some(&plan.version))
            .await
            .is_err()
    );
    assert_eq!(read(db, 2).await.token_version, 1);
    assert_eq!(notice_count(db, 2).await, 1);
    let plan2 = prepared(&ctx, 1, &freeze).await;
    assert_eq!(plan2.before, plan2.after);
    assert!(
        plan2.changed && plan2.revoke_sessions,
        "freezing already frozen still revokes old sessions"
    );
    execute(&ctx.state, &headers(1, 0), &freeze, Some(&plan2.version))
        .await
        .unwrap();
    assert_eq!(read(db, 2).await.token_version, 2);
    let unfreeze = intent("unfreeze");
    let plan = prepared(&ctx, 1, &unfreeze).await;
    assert!(plan.changed && !plan.revoke_sessions);
    execute(&ctx.state, &headers(1, 0), &unfreeze, Some(&plan.version))
        .await
        .unwrap();
    assert_eq!(
        (read(db, 2).await.status, read(db, 2).await.token_version),
        (0, 2)
    );
    let plan = prepared(&ctx, 1, &unfreeze).await;
    assert!(!plan.changed && !plan.revoke_sessions && plan.notification_count == 0);
    let count = notice_count(db, 2).await;
    execute(&ctx.state, &headers(1, 0), &unfreeze, Some(&plan.version))
        .await
        .unwrap();
    assert_eq!(notice_count(db, 2).await, count);

    let mut mute = intent("mute");
    mute.muted_until = Some("9999-12-31T23:59:59".into());
    let permanent = prepared(&ctx, 1, &mute).await;
    assert_eq!(
        permanent.after.muted_until.as_deref(),
        Some("9999-12-31T23:59:59")
    );
    assert!(!permanent.revoke_sessions);
    execute(&ctx.state, &headers(1, 0), &mute, Some(&permanent.version))
        .await
        .unwrap();
    assert_eq!(read(db, 2).await.token_version, 2);
    assert_eq!(read(db, 2).await.status, 0);
    let noop = prepared(&ctx, 1, &mute).await;
    assert!(!noop.changed && noop.notification_count == 0);
    let until = (targets::now() + chrono::Duration::hours(3))
        .format("%Y-%m-%dT%H:%M:%S")
        .to_string();
    mute.muted_until = Some(until.clone());
    let temporary = prepared(&ctx, 1, &mute).await;
    execute(&ctx.state, &headers(1, 0), &mute, Some(&temporary.version))
        .await
        .unwrap();
    assert_eq!(Account::from(&read(db, 2).await).muted_until, Some(until));
    // Direct console changes use the same mute column and transactional notice.
    let Json(legacy_result) = crate::routes::temp_user::set_user_muted(
        State(ctx.state.clone()),
        headers(1, 0),
        axum::extract::Path(2),
        Json(crate::routes::temp_user::SetMuteReq {
            muted: false,
            hours: None,
        }),
    )
    .await;
    assert_eq!(legacy_result.code, 200, "{}", legacy_result.message);
    assert!(read(db, 2).await.muted_until.is_none());
    assert!(
        execute(&ctx.state, &headers(1, 0), &mute, Some(&temporary.version))
            .await
            .is_err()
    );

    // A prepared temporary mute that expires before execution requires fresh confirmation.
    let mut expiring = intent("mute");
    expiring.muted_until = Some(
        (targets::now() + chrono::Duration::seconds(2))
            .format("%Y-%m-%dT%H:%M:%S")
            .to_string(),
    );
    let expires = prepared(&ctx, 1, &expiring).await;
    tokio::time::sleep(std::time::Duration::from_millis(2100)).await;
    assert!(execute(
        &ctx.state,
        &headers(1, 0),
        &expiring,
        Some(&expires.version)
    )
    .await
    .is_err());
    assert!(read(db, 2).await.muted_until.is_none());

    // A target ABA and actor privilege ABA both invalidate plans despite equal public snapshots.
    let ready = prepared(&ctx, 1, &freeze).await;
    sql(db,"UPDATE \"user\" SET muted_until='2099-01-01' WHERE id=2; UPDATE \"user\" SET muted_until=NULL WHERE id=2").await;
    assert!(
        execute(&ctx.state, &headers(1, 0), &freeze, Some(&ready.version))
            .await
            .is_err()
    );
    let ready = prepared(&ctx, 1, &freeze).await;
    sql(db,"UPDATE \"user\" SET role='admin' WHERE id=1; UPDATE \"user\" SET role='superadmin' WHERE id=1").await;
    assert!(
        execute(&ctx.state, &headers(1, 0), &freeze, Some(&ready.version))
            .await
            .is_err()
    );
    // Unrelated quota counters do not invalidate business confirmation.
    let ready = prepared(&ctx, 1, &freeze).await;
    sql(
        db,
        "UPDATE \"user\" SET chat_quota_used=chat_quota_used+1 WHERE id IN(1,2)",
    )
    .await;
    execute(&ctx.state, &headers(1, 0), &freeze, Some(&ready.version))
        .await
        .unwrap();

    let mut role = intent("set_role");
    role.role = Some("admin".into());
    assert!(execute(&ctx.state, &headers(4, 0), &role, None)
        .await
        .is_err());
    let ready = prepared(&ctx, 1, &role).await;
    execute(&ctx.state, &headers(1, 0), &role, Some(&ready.version))
        .await
        .unwrap();
    assert_eq!(read(db, 2).await.role, "admin");
    assert!(
        execute(&ctx.state, &headers(4, 0), &freeze, None)
            .await
            .is_err(),
        "peer admin denied"
    );
    assert!(execute(
        &ctx.state,
        &headers(1, 0),
        &Intent {
            target: Target {
                id: Some(1),
                username: None
            },
            ..freeze.clone()
        },
        None
    )
    .await
    .is_err());
    let target = read(db, 2).await;
    let ready = prepared(&ctx, 1, &unfreeze).await;
    sql(db, "UPDATE \"user\" SET role='user' WHERE id=1").await;
    assert!(
        execute(&ctx.state, &headers(1, 0), &unfreeze, Some(&ready.version))
            .await
            .is_err()
    );
    sql(
        db,
        "UPDATE \"user\" SET role='superadmin',token_version=1 WHERE id=1",
    )
    .await;
    assert!(
        execute(&ctx.state, &headers(1, 0), &unfreeze, None)
            .await
            .is_err(),
        "revoked actor token denied in transaction"
    );
    sql(db, "UPDATE \"user\" SET token_version=0 WHERE id=1").await;
    assert_eq!(read(db, 2).await, target);

    // Mandatory notice failure must roll back the account update and revision in the actual DB.
    sql(db,"CREATE FUNCTION reject_account_notice() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'injected notice failure'; END; $$; CREATE TRIGGER reject_notice BEFORE INSERT ON user_notification FOR EACH ROW EXECUTE FUNCTION reject_account_notice()").await;
    let before = read(db, 2).await;
    let rev_before = targets::revision(db, 2).await.unwrap();
    let count = notice_count(db, 2).await;
    assert!(execute(&ctx.state, &headers(1, 0), &unfreeze, None)
        .await
        .is_err());
    assert_eq!(read(db, 2).await, before);
    assert_eq!(targets::revision(db, 2).await.unwrap(), rev_before);
    assert_eq!(notice_count(db, 2).await, count);
    sql(db, "DROP TRIGGER reject_notice ON user_notification").await;
    // An update failure also produces no partial notice.
    sql(
        db,
        "ALTER TABLE \"user\" ADD CONSTRAINT reject_status CHECK(status=1) NOT VALID",
    )
    .await;
    assert!(execute(&ctx.state, &headers(1, 0), &unfreeze, None)
        .await
        .is_err());
    assert_eq!(notice_count(db, 2).await, count);
    assert_eq!(read(db, 2).await, before);
    sql(db, "ALTER TABLE \"user\" DROP CONSTRAINT reject_status").await;
    // Every account write route uses the administrator middleware.
    use axum::{body::Body, http::Request};
    for path in [
        "/api/protected/account-actions/prepare",
        "/api/protected/account-actions",
        "/api/temp-users/2/status",
        "/api/temp-users/2/mute",
        "/api/temp-users/2/role",
    ] {
        let app = crate::routes::create_router(state(scoped_db(&ctx.url, &ctx.schema).await));
        let response = app
            .oneshot(
                Request::builder()
                    .method("POST")
                    .uri(path)
                    .header("content-type", "application/json")
                    .header(
                        "authorization",
                        format!(
                            "Bearer {}",
                            crate::auth_jwt::create_token(3, "superadmin", 0)
                        ),
                    )
                    .body(Body::from("{}"))
                    .unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(
            response.status(),
            axum::http::StatusCode::FORBIDDEN,
            "{path}"
        );
    }
    assert_eq!(
        user::Entity::find_by_id(3)
            .one(db)
            .await
            .unwrap()
            .unwrap()
            .status,
        0
    );
    // Exercise authorized prepare and execute through the complete Router, not a handler-only harness.
    use http_body_util::BodyExt;
    let app = crate::routes::create_router(state(scoped_db(&ctx.url, &ctx.schema).await));
    let body = serde_json::to_vec(&unfreeze).unwrap();
    let response = app
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/protected/account-actions/prepare")
                .header("content-type", "application/json")
                .header(
                    "authorization",
                    format!("Bearer {}", crate::auth_jwt::create_token(1, "user", 0)),
                )
                .body(Body::from(body))
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), axum::http::StatusCode::OK);
    let result: serde_json::Value =
        serde_json::from_slice(&response.into_body().collect().await.unwrap().to_bytes()).unwrap();
    assert_eq!(result["code"], 200);
    let version = result["data"]["plan"]["version"].as_str().unwrap();
    assert_eq!(
        result["data"]["intent"],
        serde_json::to_value(&unfreeze).unwrap()
    );
    let app = crate::routes::create_router(state(scoped_db(&ctx.url, &ctx.schema).await));
    let response = app
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/protected/account-actions")
                .header("content-type", "application/json")
                .header(
                    "authorization",
                    format!("Bearer {}", crate::auth_jwt::create_token(1, "user", 0)),
                )
                .body(Body::from(
                    serde_json::to_vec(&json!({"version":version,"intent":unfreeze})).unwrap(),
                ))
                .unwrap(),
        )
        .await
        .unwrap();
    let result: serde_json::Value =
        serde_json::from_slice(&response.into_body().collect().await.unwrap().to_bytes()).unwrap();
    assert_eq!(result["code"], 200);
    assert_eq!(read(db, 2).await.status, 0);
    // Two simultaneous executions of one confirmed revision can commit only one revocation/notice.
    let plan = prepared(&ctx, 1, &freeze).await;
    let before_ver = read(db, 2).await.token_version;
    let before_count = notice_count(db, 2).await;
    let auth = headers(1, 0);
    let (left, right) = tokio::join!(
        execute(&ctx.state, &auth, &freeze, Some(&plan.version)),
        execute(&ctx.state, &auth, &freeze, Some(&plan.version))
    );
    assert_eq!(usize::from(left.is_ok()) + usize::from(right.is_ok()), 1);
    assert_eq!(read(db, 2).await.token_version, before_ver + 1);
    assert_eq!(notice_count(db, 2).await, before_count + 1);
    // Direct console status and role changes use the shared service.
    for (path, body, expected_role, token_increment) in [
        (
            "/api/temp-users/2/status",
            json!({"frozen":false}),
            "admin",
            0,
        ),
        ("/api/temp-users/2/role", json!({"role":"zako"}), "zako", 1),
    ] {
        let before = read(db, 2).await;
        let notices_before = notice_count(db, 2).await;
        let app = crate::routes::create_router(state(scoped_db(&ctx.url, &ctx.schema).await));
        let response = app
            .oneshot(
                Request::builder()
                    .method("POST")
                    .uri(path)
                    .header("content-type", "application/json")
                    .header(
                        "authorization",
                        format!("Bearer {}", crate::auth_jwt::create_token(1, "user", 0)),
                    )
                    .body(Body::from(serde_json::to_vec(&body).unwrap()))
                    .unwrap(),
            )
            .await
            .unwrap();
        let result: serde_json::Value =
            serde_json::from_slice(&response.into_body().collect().await.unwrap().to_bytes())
                .unwrap();
        assert_eq!(result["code"], 200, "{path}: {result}");
        let after = read(db, 2).await;
        assert_eq!(after.status, 0);
        assert_eq!(after.role, expected_role);
        assert_eq!(after.token_version, before.token_version + token_increment);
        assert_eq!(notice_count(db, 2).await, notices_before + 1);
    }
    // Superadmins can repair an unregistered role under the same authorization policy.
    sql(
        db,
        "UPDATE \"user\" SET role='historical_unknown' WHERE id=2",
    )
    .await;
    let mut repair = intent("set_role");
    repair.role = Some("user".to_owned());
    let plan = prepared(&ctx, 1, &repair).await;
    assert_eq!(plan.before.role, "historical_unknown");
    execute(&ctx.state, &headers(1, 0), &repair, Some(&plan.version))
        .await
        .unwrap();
    assert_eq!(read(db, 2).await.role, "user");
    db.execute_unprepared("SELECT 1").await.unwrap();
    ctx.close().await;
}

#[tokio::test]
async fn postgres_account_eligibility_is_authoritative_readonly_and_not_an_execution_grant() {
    use axum::{
        body::{to_bytes, Body},
        http::{Request, StatusCode},
    };
    use sea_orm::{ConnectionTrait, DatabaseBackend, Statement};
    let Ok(url) = std::env::var("TEST_PG_URL") else {
        assert!(std::env::var_os("CI").is_none(), "CI requires TEST_PG_URL");
        return;
    };
    let ctx = PgContext::new(url).await;
    sql(&ctx.state.db, "INSERT INTO \"user\"(id,username,nickname,role) VALUES (6,'other_root','root','superadmin'),(7,'unknown_role','unknown','unregistered')").await;
    let snapshot = |db: sea_orm::DatabaseConnection| async move {
        let value = db
            .query_one(Statement::from_string(
                DatabaseBackend::Postgres,
                "SELECT jsonb_agg(to_jsonb(u) ORDER BY id) AS snapshot FROM \"user\" u".to_owned(),
            ))
            .await
            .unwrap()
            .unwrap()
            .try_get::<serde_json::Value>("", "snapshot")
            .unwrap();
        db.close().await.unwrap();
        value
    };
    let before = snapshot(scoped_db(&ctx.url, &ctx.schema).await).await;
    let app = crate::routes::create_router(state(scoped_db(&ctx.url, &ctx.schema).await));
    for (actor, target, action, role, reason) in [
        (4, 4, "mute", None, Some("self_target")),
        (4, 1, "mute", None, Some("target_superadmin")),
        (1, 6, "mute", None, Some("target_superadmin")),
        (4, 5, "mute", None, Some("peer_admin")),
        (4, 2, "mute", None, None),
        (1, 5, "mute", None, None),
        (4, 7, "mute", None, Some("target_role_unknown")),
        (4, 5, "freeze", None, Some("peer_admin")),
        (4, 2, "unfreeze", None, None),
        (4, 2, "unmute", None, None),
        (4, 2, "set_role", Some("admin"), Some("admin_assign_tier")),
        (4, 5, "set_role", Some("user"), Some("admin_target_tier")),
        (
            1,
            2,
            "set_role",
            Some("superadmin"),
            Some("role_not_assignable"),
        ),
        (1, 2, "set_role", Some("admin"), None),
        (1, 7, "set_role", Some("user"), None),
    ] {
        let uri = format!(
            "/api/protected/account-actions/eligibility?accountId={target}&action={action}{}",
            role.map(|role| format!("&role={role}")).unwrap_or_default()
        );
        let response = app
            .clone()
            .oneshot(
                Request::get(uri)
                    .header("authorization", headers(actor, 0)["authorization"].clone())
                    .body(Body::empty())
                    .unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        let body: serde_json::Value =
            serde_json::from_slice(&to_bytes(response.into_body(), 8192).await.unwrap()).unwrap();
        assert_eq!(body["data"]["accountId"], target);
        assert_eq!(body["data"]["action"], action);
        assert_eq!(body["data"]["role"], serde_json::to_value(role).unwrap());
        assert_eq!(body["data"]["allowed"], reason.is_none());
        assert_eq!(
            body["data"]["reasonCode"],
            serde_json::to_value(reason).unwrap()
        );
        assert!(body["data"]["message"]
            .as_str()
            .is_some_and(|text| !text.is_empty()));
        assert_eq!(body["data"].as_object().unwrap().len(), 6);
        let text = body.to_string();
        for secret in [
            "sensitive-password",
            "password",
            "tokenVersion",
            "accountActionVersion",
            "nickname",
        ] {
            assert!(!text.contains(secret));
        }
    }
    let delegated = crate::auth_jwt::delegation::issue(
        4,
        "superadmin",
        0,
        crate::auth_jwt::delegation::Scope::Tools,
        chrono::Utc::now().timestamp() as usize,
    )
    .expect("account policy integration requires BLOG_DELEGATION_SECRET");
    let response = app
        .oneshot(
            Request::get("/api/protected/account-actions/eligibility?accountId=5&action=mute")
                .header("authorization", format!("Bearer {delegated}"))
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    let body: serde_json::Value =
        serde_json::from_slice(&to_bytes(response.into_body(), 8192).await.unwrap()).unwrap();
    assert_eq!(body["data"]["allowed"], false);
    assert_eq!(body["data"]["reasonCode"], "peer_admin");
    assert_eq!(
        snapshot(scoped_db(&ctx.url, &ctx.schema).await).await,
        before
    );
    for id in 1..=7 {
        assert_eq!(notice_count(&ctx.state.db, id).await, 0);
    }
    sql(
        &ctx.state.db,
        "UPDATE \"user\" SET role='superadmin' WHERE id=2",
    )
    .await;
    let request: PrepareRequest = serde_json::from_value(json!({
        "action":"mute", "target":{"id":2}, "hours":1,
    }))
    .unwrap();
    let Json(response) = prepare(State(ctx.state.clone()), headers(4, 0), Json(request)).await;
    assert_ne!(
        response.code, 200,
        "a past allowed eligibility check never grants execution authority"
    );
    assert_eq!(response.message, "不能禁言超级管理员账号");
    assert!(read(&ctx.state.db, 2).await.muted_until.is_none());
    assert_eq!(notice_count(&ctx.state.db, 2).await, 0);
    ctx.close().await;
}

#[tokio::test]
async fn postgres_account_eligibility_rejects_bad_arguments_missing_targets_and_invalid_actors() {
    use axum::{
        body::{to_bytes, Body},
        http::{Request, StatusCode},
    };
    let Ok(url) = std::env::var("TEST_PG_URL") else {
        assert!(std::env::var_os("CI").is_none(), "CI requires TEST_PG_URL");
        return;
    };
    let ctx = PgContext::new(url).await;
    let app = crate::routes::create_router(state(scoped_db(&ctx.url, &ctx.schema).await));
    for (actor, version, query, expected) in [
        (0, 0, "accountId=2&action=mute", StatusCode::UNAUTHORIZED),
        (2, 0, "accountId=2&action=mute", StatusCode::FORBIDDEN),
        (4, 8, "accountId=2&action=mute", StatusCode::UNAUTHORIZED),
        (4, 0, "accountId=99&action=mute", StatusCode::NOT_FOUND),
        (4, 0, "accountId=0&action=mute", StatusCode::BAD_REQUEST),
        (4, 0, "accountId=2&action=set_role", StatusCode::BAD_REQUEST),
        (
            4,
            0,
            "accountId=2&action=mute&role=user",
            StatusCode::BAD_REQUEST,
        ),
        (
            4,
            0,
            "accountId=2&action=set_role&role=unregistered",
            StatusCode::BAD_REQUEST,
        ),
        (
            4,
            0,
            "accountId=2&action=mute&hours=1",
            StatusCode::BAD_REQUEST,
        ),
    ] {
        let mut request = Request::get(format!(
            "/api/protected/account-actions/eligibility?{query}"
        ));
        if actor > 0 {
            request = request.header(
                "authorization",
                headers(actor, version)["authorization"].clone(),
            );
        }
        let response = app
            .clone()
            .oneshot(request.body(Body::empty()).unwrap())
            .await
            .unwrap();
        assert_eq!(response.status(), expected, "{query}");
        let bytes = to_bytes(response.into_body(), 8192).await.unwrap();
        assert!(!String::from_utf8_lossy(&bytes).contains("sensitive-password"));
    }
    sql(&ctx.state.db, "UPDATE \"user\" SET status=1 WHERE id=4").await;
    let response = app
        .oneshot(
            Request::get("/api/protected/account-actions/eligibility?accountId=2&action=mute")
                .header("authorization", headers(4, 0)["authorization"].clone())
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::UNAUTHORIZED);
    ctx.close().await;
}
