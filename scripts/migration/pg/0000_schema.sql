CREATE OR REPLACE TRIGGER "trg_knowledge_base_updated_at" BEFORE UPDATE ON "knowledge_base"
  FOR EACH ROW WHEN (OLD.* IS DISTINCT FROM NEW.*) EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER "trg_note_comment_updated_at" BEFORE UPDATE ON "note_comment"
