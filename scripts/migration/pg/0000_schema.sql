-- ── `ON UPDATE CURRENT_TIMESTAMP` 的替身（PG 没有这一档）
-- MySQL 的规则是「**别的列**变了才自动刷新；updated_at 被显式赋值时不刷新；
-- 整行没变也不刷新」。下面这两件合起来复刻它：
--   · `WHEN (OLD.* IS DISTINCT FROM NEW.*)` —— 整行没变就不进函数；
--   · 函数里 `IS NOT DISTINCT FROM` 那一格 —— 显式赋了新值的照用新值。
-- ⚠️ 复刻不到的一格（如实记）：显式把 updated_at 赋成**原来的值**、同时改了别的列。
--    MySQL 认「显式赋值」⇒ 不动；本实现看不出「没赋值」与「赋了个同值」的差别 ⇒ 会刷成 now()。
--    本库现有代码里这么写的只有 conversation / note 两张表，而它们**没有** ON UPDATE
--    （见 routes/conversation.rs:408、routes/tags.rs:572）⇒ 今天踩不到；
--    将来谁在这 9 张表上这么写，就是这一格。
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := now();
  END IF;
  RETURN NEW;
END $$;

CREATE OR REPLACE TRIGGER "trg_agent_task_updated_at" BEFORE UPDATE ON "agent_task"
  FOR EACH ROW WHEN (OLD.* IS DISTINCT FROM NEW.*) EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER "trg_announcement_updated_at" BEFORE UPDATE ON "announcement"
  FOR EACH ROW WHEN (OLD.* IS DISTINCT FROM NEW.*) EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER "trg_chat_summary_updated_at" BEFORE UPDATE ON "chat_summary"
  FOR EACH ROW WHEN (OLD.* IS DISTINCT FROM NEW.*) EXECUTE FUNCTION set_updated_at();
