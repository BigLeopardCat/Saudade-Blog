DO $$
DECLARE r record;
BEGIN
  -- ① 先表（含视图/物化视图/分区表）
  -- **顺序不是随便排的**：下一段的序列依赖这里的先后。见 ②。
  FOR r IN
    SELECT c.relname, c.relkind
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public'
       AND c.relkind IN ('r', 'p', 'v', 'm')
       AND pg_get_userbyid(c.relowner) <> 'saudade_app'
       AND NOT EXISTS (SELECT 1 FROM pg_depend d
                        WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid
                          AND d.deptype = 'e')
  LOOP
    EXECUTE format('ALTER %s public.%I OWNER TO saudade_app',
      CASE r.relkind WHEN 'v' THEN 'VIEW'
                     WHEN 'm' THEN 'MATERIALIZED VIEW'
                     ELSE 'TABLE' END, r.relname);
  END LOOP;

  -- ② 再序列，但**只动不归表管的那些**
  -- 直接改会报：
  --   ERROR: cannot change owner of sequence "announcement_id_seq"
  --   DETAIL: Sequence "announcement_id_seq" is linked to table "announcement".
  -- 自增列（`GENERATED BY DEFAULT AS IDENTITY`）的序列**不能单独改 owner** ——
  -- 它归它的表所有，`ALTER TABLE … OWNER TO` 会**连带**把它的 owner 一起改掉
  -- （PG 的 `change_owner_recurse_to_sequences`）。所以正确做法是"先改表"（①），
  -- 那些序列就**自动**跟着过来了；这一段只是兜住**不挂在任何表上**的独立序列。
  -- `deptype IN ('i','a')`：'i' = identity 列的内部依赖，'a' = serial 的 auto 依赖。
  FOR r IN
    SELECT c.relname
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind = 'S'
       AND pg_get_userbyid(c.relowner) <> 'saudade_app'
       AND NOT EXISTS (SELECT 1 FROM pg_depend d
                        WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid
                          AND d.deptype = 'e')
       AND NOT EXISTS (SELECT 1 FROM pg_depend d
                        WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid
                          AND d.refclassid = 'pg_class'::regclass
                          AND d.deptype IN ('i', 'a'))
  LOOP
    EXECUTE format('ALTER SEQUENCE public.%I OWNER TO saudade_app', r.relname);
  END LOOP;

  -- ③ 最后是函数
  -- 触发器函数（那套 ON UPDATE）也一起改，保持 owner 一致。
  -- 它今天能执行只是因为 PG 对函数的 EXECUTE **默认授给 PUBLIC** —— 那是巧合不是设计。
  FOR r IN
    SELECT p.oid::regprocedure::text AS sig
      FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public'
       AND pg_get_userbyid(p.proowner) <> 'saudade_app'
       AND NOT EXISTS (SELECT 1 FROM pg_depend d
                        WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid
                          AND d.deptype = 'e')
  LOOP
    EXECUTE format('ALTER FUNCTION %s OWNER TO saudade_app', r.sig);
  END LOOP;
END $$;

-- 复核
-- ① 三个数都该是「全部 / 全部」
SELECT '表' AS 对象,
       count(*) FILTER (WHERE has_table_privilege('saudade_app', c.oid, 'SELECT'))::text
       || ' / ' || count(*)::text AS 可读
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = 'public' AND c.relkind = 'r'
UNION ALL
SELECT '序列',
       count(*) FILTER (WHERE has_sequence_privilege('saudade_app', c.oid, 'USAGE'))::text
       || ' / ' || count(*)::text
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = 'public' AND c.relkind = 'S';

-- ② 反向闸：**pgvector 的成员一个都不许被动过**（该恒为 0 行）
SELECT '被误改 owner 的扩展成员' AS 闸, count(*)::text || ' 个（该是 0）' AS 读数
  FROM pg_depend d
  JOIN pg_class c ON d.classid = 'pg_class'::regclass AND c.oid = d.objid
  JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
 WHERE d.deptype = 'e' AND pg_get_userbyid(c.relowner) = 'saudade_app'
UNION ALL
-- **`nspname = 'public'` 这道过滤不能省**：首版漏了它，读数 40 而"该是 37" ⇒ 看着像判据坏了，
-- 其实多出来的是 **plpgsql 那 3 个**（`plpgsql_call_handler` / `_inline_handler` / `_validator`，
-- 住在 `pg_catalog`）—— 它们也是扩展成员、也不归 saudade_app，被一起数进来了。
-- 判据本身没错，是**射程**写错了：本文件只管 `public`，闸也必须只盯 `public`。
SELECT '扩展函数 owner 仍是原主',
       count(*)::text || ' 个（该是 37）'
  FROM pg_depend d
  JOIN pg_proc p ON d.classid = 'pg_proc'::regclass AND p.oid = d.objid
  JOIN pg_namespace n ON n.oid = p.pronamespace AND n.nspname = 'public'
 WHERE d.deptype = 'e' AND pg_get_userbyid(p.proowner) <> 'saudade_app';
