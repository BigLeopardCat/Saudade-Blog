CREATE TABLE IF NOT EXISTS image_folder (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id integer REFERENCES image_folder(id) ON DELETE RESTRICT,
    name varchar(80) NOT NULL CHECK (length(btrim(name)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS image_folder_sibling_name
    ON image_folder (COALESCE(parent_id, 0), lower(name));

CREATE TABLE IF NOT EXISTS image_metadata (
    image_id integer PRIMARY KEY REFERENCES images(image_key) ON DELETE CASCADE,
    display_name varchar(255),
    description varchar(2000) NOT NULL DEFAULT '',
    folder_id integer REFERENCES image_folder(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS image_metadata_folder ON image_metadata(folder_id, image_id DESC);

CREATE TABLE IF NOT EXISTS image_favorite (
    image_id integer NOT NULL REFERENCES images(image_key) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, image_id)
);
