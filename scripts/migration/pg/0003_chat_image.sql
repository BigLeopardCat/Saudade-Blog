-- 聊天的图片落库：`chat_image`（20261018）。
--
-- 跑法（**以应用角色跑**，不是 `sudo -u postgres`）：
--   psql -h 127.0.0.1 -U saudade_app -d saudade_blog -X -v ON_ERROR_STOP=1 -f - < 本文件
-- 理由见下面《为什么以应用角色跑》一节。可反复跑（`IF NOT EXISTS` + 幂等）。
--
-- ── 本文件是手写的（与 `0000_schema.sql` 不同源）────────────────────────────
-- 那一份由 `mysql2pg.py` 从 MySQL 的 `information_schema` 生成，而这一张表
-- **MySQL 那边没有对应物**（图片从来没进过任何库）。所以「改结构 = 先改 MySQL
-- 再重跑生成器」那条纪律在这里不适用，改这里就是改这里。
-- ⚠️ 代价说清楚：`verify_parity.py` 是拿生成物逐列对账的，手写表进它的
-- `HAND_WRITTEN` 豁免之后，**没有任何东西在核对这张表的列**
-- （列 diff 只遍历 MySQL 那侧的表）。这是手写表的既定代价，别读成"已验"。
--
-- ── 为什么值得做（不是"记录好看一点"这种理由）──────────────────────────────
-- 在此之前图片**从来不落库**：Rust 把它透传给 Python agent 之后丢掉，只在
-- `chat_history.content` 末尾拼 `[图片]` / `[图片×N]` 标记。于是聊天记录是**不完整的**
-- ——前端在会话内能用内存里的 dataURL 渲染真图，刷新/换设备之后只剩一个占位块
-- 「ⓘ图片已过期」。实测 20261018：库里 1188 条消息中有 7 条带那个标记，
-- 那 7 张图**已经永久丢了**（只存在于当时那个浏览器里）。这一刀之后不再产生新的丢失。
--
-- ── 只做展示：模型仍然看不到历史图 ─────────────────────────────────────────
-- 注入给 agent 的历史仍是 `role`/`content` 字符串 + `[图片]` 标记（一个字节没改）。
-- 「让模型回忆旧图」是另一件事（要改历史轮的消息形状），取舍与触发条件写在
-- agent 仓 `docs/adr/adr-0013-chat-image-persistence.md`。
--
-- ── 为什么另开一张表，而不是给 `chat_history` 加一列 ────────────────────────
-- 热路径（`GET /api/chat/history` 的 50 条、发给 agent 的 21 条）**一个字节都不多读**。
-- 加列的话，"排除大字段"就只能靠"记得在每个查询点写 `select_only`"这条纪律，
-- 漏一处就是"历史接口变慢"而没人知道。另开一张表让这件事**结构性**成立。
--
-- ── 外键：本仓 chat 家族的第一条 ────────────────────────────────────────────
-- `chat_history` / `chat_summary` / `execution_log` / `conversation` 一直是**应用层级联**
-- （`conversation.rs` 明写"无 DB 外键——与全项目'实体零关系'惯例一致"）。
-- 这里破例，理由只有一个但足够硬：删 `chat_history` 的地方有 **5 处**
--   · `chat.rs` 的 `discard_handler`（停止生成的全删语义）
--   · `chat.rs` 的每会话 500 条上限"删头"
--   · `chat.rs` 的 `DiscardAbortedExchange::drop`（断连清理）
--   · `conversation.rs` 的 `delete_conversation`（事务内）
--   · `temp_user.rs` 的删临时账号
-- 漏一处 = 图片**永久孤儿**，而且**没有任何东西会红**。外键把"五处人工同步"
-- 变成结构性事实。schema 里本来就有 12 条外键，全在"父行子表"形状上
-- （`note_like` / `note_view` / `user_favorite` / `tag_two`），这张表是同一种形状。
--
-- ── 为什么以应用角色跑 ──────────────────────────────────────────────────────
-- `0000` / `0001` 一直是通过 `sudo -n -u postgres psql` 跑的 ⇒ owner 全是 `postgres`，
-- 而应用角色 `saudade_app` 一格权限都没有；这个坏法很隐蔽：**连接测试是绿的**，
-- 第一条业务 SQL 才 403（见 `0002_owner_to_app.sql` 头注）。以 `saudade_app` 跑这一份，
-- 表与它的 identity 序列**天生就归应用**，不必回头重跑 `0002`。
-- （重跑 `0002` 也无害：它按 `relowner` 现取差集。）
--
-- ── 索引名：PG 是 schema 级全局唯一，重名会被 `IF NOT EXISTS` 静默吞掉 ──────
-- 只印一行 NOTICE，不报错 —— 首跑实测 `execution_log.idx_conv_id` 就是这么丢的
-- （所以 `chat_history` / `execution_log` 那两个都改名成了 `<表>_idx_conv_id`）。
-- 本表这个索引名与现存 45 个都不同。

CREATE TABLE IF NOT EXISTS "chat_image" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "message_id" integer NOT NULL,
  -- 同一条消息内的次序（前端发的是一个数组，顺序就是展示顺序）。
  -- `(message_id, seq)` 唯一 ⇒ 重放/双标签页重复提交挡在库这一层。
  "seq" smallint NOT NULL,
  -- **完整 dataURL**（含 `data:image/…;base64,` 前缀），原样存原样取。
  -- 不拆出 `mime`：它就在前缀里，拆出来就是一处会漂的手工同步。
  -- 不存 `bytes`：base64 长度能推出来，存一份是同一件事写两处。
  -- 类型是 `text` 而不是 `bytea`：前端要的就是那个字符串，落库再编码回来
  -- 只多一次转码、不多任何东西（也让"读回来的与写进去的逐字相等"成了一条
  -- 能写的判据）。PG 的 TOAST 会把大值挪出主表，主表行本身不长。
  "data" text NOT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "chat_image_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "fk_chat_image_msg" FOREIGN KEY ("message_id")
    REFERENCES "chat_history" ("id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "chat_image_uk_msg_seq" ON "chat_image" ("message_id", "seq");
