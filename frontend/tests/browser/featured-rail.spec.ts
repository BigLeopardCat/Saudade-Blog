import {test, expect} from './sandbox'
test.use({entry: 'featured-rail'})
for (const {width, count, groups} of [{width:375,count:1,groups:7}, {width:760,count:2,groups:4}, {width:1440,count:3,groups:3}]) {
    test(`segmented navigation previews the exact pinned group without moving it at ${width}px`, async ({page, sandboxURL}) => {
        await page.setViewportSize({width, height: 900})
        await page.emulateMedia({reducedMotion:'reduce'})
        await page.goto(sandboxURL)
        const root = page.getByRole('region', {name: '置顶'})
        const segments = root.getByRole('group', {name: '置顶内容分组'}).getByRole('button')
        await expect(segments).toHaveCount(groups)
        expect(await segments.allTextContents()).toEqual(Array(groups).fill(''))
        const track = root.locator('.featuredTrack')
        const before = await track.evaluate(el => el.style.transform)
        await segments.nth(1).hover()
        const preview = root.locator('.featuredPreview')
        await expect(preview.locator('.ArticleCard')).toHaveCount(count)
        await expect(preview.locator('.ArticleNumber')).toHaveText(Array.from({length:count},(_,index)=>String(count+index+1).padStart(2,'0')))
        expect(await track.evaluate(el => el.style.transform)).toBe(before)
        const bounds = (await preview.boundingBox())!
        expect(bounds.x).toBeGreaterThanOrEqual(0)
        expect(bounds.x + bounds.width).toBeLessThanOrEqual(width + 1)
        await segments.nth(1).click()
        await expect(segments.nth(1)).toHaveAttribute('aria-pressed', 'true')
        await expect.poll(() => track.evaluate(el => new DOMMatrix(getComputedStyle(el).transform).m41)).toBeLessThan(-100)
        expect(await root.getByRole('button', {name: /暂停|播放|上一|下一/}).count()).toBe(0)
        expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1)
        await root.screenshot({path:test.info().outputPath('segmented-preview.png')})
        await page.getByRole('button', {name: '切换昼夜'}).click()
        await segments.nth(1).hover()
        await root.screenshot({path:test.info().outputPath('segmented-preview-dark.png')})
    })
}

test('rail and segment fill advance together, pause on cards or previews, and resume after pointer selection', async ({page, sandboxURL}) => {
    await page.setViewportSize({width:1440,height:900})
    await page.clock.install()
    await page.goto(sandboxURL)
    const root = page.getByRole('region', {name:'置顶'})
    const track = root.locator('.featuredTrack')
    const offset = () => track.evaluate(el => new DOMMatrix(getComputedStyle(el).transform).m41)
    const segments = root.getByRole('group', {name:'置顶内容分组'}).getByRole('button')
    await expect(segments).toHaveCount(3)
    await page.mouse.move(0,0)
    await page.clock.runFor(600)
    const moving = await offset()
    expect(moving).toBeLessThan(-1)
    expect(await segments.first().locator('.featuredSegment > span').evaluate(el => new DOMMatrix(getComputedStyle(el).transform).a)).toBeGreaterThan(0)
    const firstCover = (await root.locator('.ArticleCover').first().boundingBox())!
    await page.mouse.move(firstCover.x + firstCover.width / 2, firstCover.y + firstCover.height / 2)
    await expect(root).toHaveAttribute('data-paused','true')
    const stopped = await offset()
    await page.clock.runFor(500)
    expect(await offset()).toBe(stopped)
    await segments.nth(1).hover()
    const preview = root.locator('.featuredPreview')
    await expect(preview).toBeVisible()
    await preview.hover()
    await page.clock.runFor(500)
    expect(await offset()).toBe(stopped)
    await segments.last().click()
    const selected = await offset()
    await page.mouse.move(0,0)
    await expect(root).toHaveAttribute('data-paused','false')
    await page.clock.runFor(24000)
    const wrapped = await offset()
    expect(wrapped).toBeLessThan(0)
    expect(wrapped).toBeGreaterThan(selected + 100)
    await segments.first().focus()
    await page.keyboard.press('ArrowRight')
    await expect(segments.nth(1)).toBeFocused()
    await expect(root).toHaveAttribute('data-paused','true')
    const keyboardStopped = await offset()
    await page.clock.runFor(500)
    expect(await offset()).toBe(keyboardStopped)
    await page.keyboard.press('Enter')
    await expect(segments.nth(1)).toHaveAttribute('aria-pressed','true')
    await page.keyboard.press('Escape')
    await expect(preview).toHaveCount(0)
    await page.getByRole('button', {name:'切换空列表'}).click()
    await expect(root).toHaveCount(0)
    await page.getByRole('button', {name:'切换空列表'}).click()
    await expect(root).toBeVisible()
    await expect(segments).toHaveCount(3)
})

test('admin preview uses the same card, live article content, and crop geometry as the homepage', async ({page,sandboxURL}) => {
    await page.setViewportSize({width:1440,height:900})
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.goto(sandboxURL)
    const ordinary = page.getByTestId('ordinary-card').locator('.ArticleCard')
    const snapshot = (card: typeof ordinary) => card.evaluate(el => {
        const rect = el.getBoundingClientRect(), cover = el.querySelector('.ArticleCover')!.getBoundingClientRect()
        return {width:rect.width,height:rect.height,coverWidth:cover.width,coverHeight:cover.height,title:el.querySelector('.ArticleTitle')!.textContent}
    })
    const expected = await snapshot(ordinary)
    await page.getByRole('button',{name:'预览实际卡片'}).click()
    const dialog = page.getByRole('dialog')
    const preview = dialog.locator('.ccActualCard .ArticleCard')
    await expect(preview.locator('.ArticleTitle')).toHaveText('春日手记 1')
    await expect(preview).toContainText('写作者')
    expect(await snapshot(preview)).toEqual(expected)
    await expect(preview.locator('a')).toHaveCount(0)
})

