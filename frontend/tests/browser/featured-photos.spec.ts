import {test, expect} from './sandbox'
test.use({entry: 'featured-photos'})
test('album requests no image until opened, then only the selected photo; close restores focus', async ({page, sandboxURL}) => {
    const requests: string[] = []
    await page.route('**/api/public/featured-photos', route => route.fulfill({json: {code: 200, data: [1, 2, 3].map(imageId => ({imageId, caption: `照片 ${imageId}`, url: `/api/public/media/photo-${imageId}`}))}}))
    await page.route('**/api/public/media/*', route => {
        requests.push(new URL(route.request().url()).pathname)
        return route.fulfill({contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="600" height="400"><rect width="600" height="400" fill="#e9b4cb"/></svg>'})
    })
    await page.goto(sandboxURL)
    const stack = page.getByRole('button', {name: '打开精选相册（3 张）'})
    await expect(stack).toBeVisible()
    await stack.hover()
    await page.evaluate(() => window.scrollTo(0, 100))
    expect(requests).toEqual([])
    expect(await page.locator('img').count()).toBe(0)
    await stack.click()
    const viewer = page.getByRole('dialog', {name: '精选相册'})
    await expect(viewer.getByRole('img')).toHaveAttribute('alt', '照片 1')
    await expect.poll(() => requests.length).toBe(1)
    await viewer.getByRole('button', {name: '下一张照片'}).click()
    await expect(viewer.getByRole('img')).toHaveAttribute('alt', '照片 2')
    await expect.poll(() => requests.length).toBe(2)
    await expect(viewer.getByRole('img')).toHaveCount(1)
    expect(requests.some(url => url.endsWith('photo-3'))).toBe(false)
    await page.keyboard.press('Escape')
    await expect(viewer).toHaveCount(0)
    await expect(stack).toBeFocused()
    await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
    await stack.click()
    await page.keyboard.press('ArrowLeft')
    await expect(page.getByRole('img')).toHaveAttribute('alt', '照片 3')
    await expect.poll(() => requests.some(url => url.endsWith('photo-3'))).toBe(true)
    await page.screenshot({path: test.info().outputPath('featured-photo-viewer.png')})
})
test('empty album has no clickable stack or image', async ({page, sandboxURL}) => {
    await page.goto(sandboxURL)
    await expect(page.locator('button')).toHaveCount(0)
    await expect(page.locator('img')).toHaveCount(0)
})
